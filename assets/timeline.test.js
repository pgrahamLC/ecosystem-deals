import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

await import('./timeline.js');
const T = globalThis.Timeline;
const book = JSON.parse(readFileSync(new URL('../data/market-entry/requirements.json', import.meta.url)));
const frameworks = JSON.parse(readFileSync(new URL('../frameworks.json', import.meta.url)));
T.use(book, frameworks);
const today = '2026-11-18';
const all = T.build({today});
const text = JSON.stringify(all.rows);
assert.equal(text.includes(';'), false);
assert.equal(text.includes('\u2014'), false);
assert.equal(text.includes('£'), false);
assert.equal(text.includes('@'), false);
const glasgow = all.rows.find((row) => row.id === 'glasgow-prsa');
assert.equal(glasgow.tone, 'bidding');
assert.equal(glasgow.start, '2027-04-01');
assert.equal(glasgow.award, '2027-03-01');
assert.ok(all.opening >= 1);
const manchester = all.rows.find((row) => row.id === 'mcc');
assert.equal(manchester.tone, 'live');
assert.equal(manchester.start, '2024-03-01');
assert.equal(manchester.end, null);
const cas = all.rows.find((row) => row.id === 'national-cas');
assert.equal(cas.start, null);
assert.equal(cas.tone, 'bidding');
const html = T.html({today, area: 'Glasgow'});
assert.equal(html.includes('contracts open for assets now'), true);
assert.equal(html.includes('Glasgow PRSA'), true);
assert.equal(html.includes('dashed'), true);
const visible = html.replace(/ style="[^"]*"/g, '');
assert.equal(visible.includes('£'), false);
assert.equal(visible.includes('@'), false);
assert.equal(visible.includes(';'), false);
const man = T.build({today, area: 'Manchester'});
assert.equal(man.rows.some((row) => row.id === 'mcc'), true);
assert.equal(man.rows.some((row) => row.id === 'bristol'), false);
assert.equal(man.rows.some((row) => /Manchester long-term TA leasing/.test(row.name)), false);
const detail = T.detail('mcc', today);
assert.equal(detail.includes('The lease'), true);
assert.equal(detail.includes('10 years and a day'), true);
assert.equal(detail.includes('£'), false);
console.log('timeline tests passed', all.openNow, all.opening, all.rows.length);
